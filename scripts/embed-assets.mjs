import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = "dist/assets";
const files = [];

function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else files.push(full);
  }
}

walk(root);
const types = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".ico": "image/x-icon",
  ".map": "application/json",
  ".txt": "text/plain; charset=utf-8",
};

const entries = files.map((full) => {
  const rel = "/" + relative(root, full).replaceAll("\\\\", "/");
  const ext = rel.slice(rel.lastIndexOf("."));
  const contentType = types[ext] || "application/octet-stream";
  const body = readFileSync(full, "utf8");
  return `  ${JSON.stringify(rel)}: { contentType: ${JSON.stringify(contentType)}, body: ${JSON.stringify(body)} }`;
});

const src = `/** Generated by scripts/embed-assets.mjs. Do not edit by hand. */
export interface EmbeddedFile {
  contentType: string;
  body: string;
}

export const EMBEDDED_ASSETS: Record<string, EmbeddedFile> = {
${entries.join(",\n")}
};

function lookup(pathname: string): EmbeddedFile | undefined {
  const exact = EMBEDDED_ASSETS[pathname];
  if (exact) return exact;
  if (pathname === "/" || pathname === "") return EMBEDDED_ASSETS["/index.html"];
  if (!pathname.includes(".") && EMBEDDED_ASSETS["/index.html"]) return EMBEDDED_ASSETS["/index.html"];
  return undefined;
}

export function serveEmbedded(request: Request): Response | null {
  const url = new URL(request.url);
  const file = lookup(url.pathname);
  if (!file) return null;
  const headers = new Headers({ "content-type": file.contentType });
  if (file.contentType.startsWith("text/html")) headers.set("cache-control", "no-store");
  else headers.set("cache-control", "public, max-age=31536000, immutable");
  return new Response(file.body, { status: 200, headers });
}
`;

writeFileSync("src/worker/embedded-assets.ts", src);
console.log(`embedded ${files.length} files into src/worker/embedded-assets.ts`);
